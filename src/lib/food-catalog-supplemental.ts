import type { FoodCatalogItem, FoodSource } from "@/lib/types";

type NutritionSeed = FoodCatalogItem["nutritionPer100g"];

const DATASET_SOURCE: FoodSource = "dataset-import";

const VEG_TAGS = ["vegan", "vegetarian"];
const DAIRY_TAGS = ["vegetarian", "dairy"];
const MEAT_TAGS = ["meat"];

function nutrition(
  calories: number,
  proteinG: number,
  carbsG: number,
  fatsG: number,
  fiberG: number,
  calcium = 25,
  iron = 1.1,
  vitaminB12 = 0,
): NutritionSeed {
  return {
    calories,
    proteinG,
    carbsG,
    fatsG,
    fiberG,
    micros: {
      calcium,
      iron,
      fiber: fiberG,
      vitaminB12,
    },
  };
}

function createFood(args: {
  id: string;
  name: string;
  aliases: string[];
  tags: string[];
  nutritionPer100g: NutritionSeed;
  portionLabel: string;
  portionUnit: string;
  portionGrams: number;
  portionAliases?: string[];
  source?: FoodSource;
}): FoodCatalogItem {
  return {
    id: args.id,
    name: args.name,
    aliases: args.aliases.map((alias) => alias.toLowerCase()),
    source: args.source ?? DATASET_SOURCE,
    nutritionPer100g: args.nutritionPer100g,
    portions: [
      {
        label: args.portionLabel,
        quantity: 1,
        unit: args.portionUnit,
        grams: args.portionGrams,
        aliases: (args.portionAliases ?? []).map((alias) => alias.toLowerCase()),
      },
      {
        label: "100 gram",
        quantity: 100,
        unit: "gram",
        grams: 100,
        aliases: [],
      },
    ],
    tags: args.tags,
  };
}

function bowl(
  id: string,
  name: string,
  aliases: string[],
  tags: string[],
  nutritionPer100g: NutritionSeed,
  portionGrams = 180,
) {
  return createFood({
    id,
    name,
    aliases,
    tags,
    nutritionPer100g,
    portionLabel: "1 bowl",
    portionUnit: "bowl",
    portionGrams,
    portionAliases: ["cup", "serving"],
  });
}

function plate(
  id: string,
  name: string,
  aliases: string[],
  tags: string[],
  nutritionPer100g: NutritionSeed,
  portionGrams = 220,
) {
  return createFood({
    id,
    name,
    aliases,
    tags,
    nutritionPer100g,
    portionLabel: "1 plate",
    portionUnit: "plate",
    portionGrams,
    portionAliases: ["serving"],
  });
}

function serving(
  id: string,
  name: string,
  aliases: string[],
  tags: string[],
  nutritionPer100g: NutritionSeed,
  portionGrams = 150,
  portionLabel = "1 serving",
) {
  return createFood({
    id,
    name,
    aliases,
    tags,
    nutritionPer100g,
    portionLabel,
    portionUnit: "serving",
    portionGrams,
  });
}

function fruit(
  id: string,
  name: string,
  aliases: string[],
  nutritionPer100g: NutritionSeed,
  portionGrams: number,
  portionLabel = "1 medium",
) {
  return createFood({
    id,
    name,
    aliases,
    tags: VEG_TAGS,
    nutritionPer100g,
    portionLabel,
    portionUnit: "piece",
    portionGrams,
    portionAliases: ["serving", "piece", "fruit"],
  });
}

